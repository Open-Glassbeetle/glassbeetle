import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import {
  MESSAGE_ROLES,
  MESSAGE_STATUSES,
  type MessageRole,
  type MessageStatus,
} from '../../messages/dto/message-response.dto.js';

/**
 * Normalised token usage reported by the provider adapter.
 */
export class TokenUsageDto {
  @ApiProperty({
    description: 'Number of prompt/input tokens processed',
    example: 125,
  })
  readonly inputTokens!: number;

  @ApiProperty({
    description: 'Number of generated completion/output tokens',
    example: 42,
  })
  readonly outputTokens!: number;

  @ApiProperty({
    description: 'Total tokens processed (input + output)',
    example: 167,
  })
  readonly totalTokens!: number;

  @ApiPropertyOptional({
    description: 'Optional reasoning tokens consumed by reasoning models',
    example: 16,
  })
  readonly reasoningTokens?: number;
}

/**
 * Response returned by the non-streaming chat completions endpoint.
 *
 * Emits the created assistant message in the exact same shape as the messages endpoints,
 * augmented with the provider's reported token usage metrics.
 */
export class CompletionResponseDto {
  @ApiProperty({
    description: 'Unique message identifier (UUIDv7)',
    example: '018f3a9e-0000-7000-8000-000000000001',
  })
  readonly id!: string;

  @ApiProperty({
    description: 'Identifier of the chat this message belongs to',
    example: '018f3a9e-0000-7000-8000-000000000002',
  })
  readonly chatId!: string;

  @ApiProperty({
    description: 'Position in the chat sequence, counting from 1',
    example: 2,
  })
  readonly sequence!: number;

  @ApiProperty({
    description:
      'Role of the message sender (always "assistant" for completions)',
    enum: MESSAGE_ROLES,
    example: 'assistant',
  })
  readonly role!: MessageRole;

  @ApiProperty({
    type: String,
    description: 'Which agent produced the message',
    example: '018f3a9e-0000-7000-8000-000000000003',
    nullable: true,
  })
  readonly agentId!: string | null;

  @ApiProperty({
    description: 'Verbatim textual content generated by the model',
    example: 'Hello! How can I assist you today?',
  })
  readonly content!: string;

  @ApiProperty({
    description:
      'Generation status of the message (always "complete" for non-streaming)',
    enum: MESSAGE_STATUSES,
    example: 'complete',
  })
  readonly status!: MessageStatus;

  @ApiProperty({
    type: 'integer',
    description:
      'Token count consumed by this message, populated from provider reported output tokens.',
    example: 42,
    nullable: true,
  })
  readonly tokenCount!: number | null;

  @ApiProperty({
    description: 'Creation timestamp in ISO-8601 UTC format',
    example: '2026-10-18T00:00:00.000Z',
  })
  readonly createdAt!: string;

  @ApiPropertyOptional({
    description:
      'Detailed token usage report from the model provider if available',
    type: TokenUsageDto,
    nullable: true,
  })
  readonly usage?: TokenUsageDto | null;

  @ApiPropertyOptional({
    description:
      'For team chats, array of all assistant messages generated across the team turn sequence in order.',
    type: () => [CompletionResponseDto],
  })
  readonly messages?: CompletionResponseDto[];
}
