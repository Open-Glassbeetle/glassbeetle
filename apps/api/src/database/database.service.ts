import {
  Injectable,
  Logger,
  OnModuleDestroy,
  OnModuleInit,
  Optional,
} from '@nestjs/common';
import Database from 'better-sqlite3';
import { mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { AppConfigService } from '../config/app-config.service.js';
import { runMigrations } from './schema-migrations.js';

/**
 * Outcome of a state-modifying statement.
 *
 * A narrowed copy of `better-sqlite3`'s own result, so callers depend on this
 * service rather than on the driver's types.
 */
export interface RunResult {
  /**
   * Rows actually inserted, updated or deleted. Services use this to tell "no
   * such row" from "nothing needed changing".
   */
  changes: number;
  /**
   * SQLite's implicit rowid of the last inserted row.
   *
   * Of little use here: every table declares a `TEXT` primary key generated by
   * `newId()`, so inserts already know their identifier.
   */
  lastInsertRowid: number | bigint;
}

/**
 * SQLite database service providing connection lifecycle management,
 * schema migrations, and a thin query interface for NestJS feature modules.
 *
 * Deliberately thin: there is no ORM and no query builder, and services write
 * their own SQL. The schema in `data/` is the source of truth, and the
 * conventions for translating between its storage types and the API's JSON live
 * in `common/persistence/`.
 *
 * Every method here is synchronous, because `better-sqlite3` is. Services still
 * expose `async` methods so the HTTP layer is free of that detail and a future
 * move to an asynchronous driver does not change their signatures.
 */
@Injectable()
export class DatabaseService implements OnModuleInit, OnModuleDestroy {
  private readonly logger = new Logger(DatabaseService.name);
  private dbInstance?: Database.Database;

  constructor(
    @Optional() private readonly appConfigService?: AppConfigService,
  ) {}

  /**
   * Opens the connection when the module starts, unless one is already open.
   *
   * Falls back to an in-memory database when no `AppConfigService` is present,
   * which is how unit tests get a schema-migrated database without touching
   * the user's data directory.
   */
  onModuleInit(): void {
    if (!this.dbInstance) {
      const dbPath = this.appConfigService?.databasePath ?? ':memory:';
      this.connect(dbPath);
    }
  }

  /**
   * Closes the connection on shutdown so WAL files are checkpointed and the
   * database is left in a clean state.
   */
  onModuleDestroy(): void {
    this.close();
  }

  /**
   * Opens the SQLite connection, enables foreign keys and WAL mode,
   * and runs initial schema migrations.
   *
   * Idempotent: a second call while a connection is open does nothing.
   *
   * Both pragmas matter. SQLite leaves foreign keys off per connection, and
   * without them the `ON DELETE CASCADE` and `SET NULL` rules the schema relies
   * on would never fire. WAL mode lets reads continue during a write, which a
   * desktop UI issuing a list request while a chat is being saved depends on.
   *
   * @param dbPath - File to open. Parent directories are created as needed. The
   * default and any `file::memory:` form open an in-memory database instead,
   * which is what tests use.
   * @throws Error if the JSON1 extension is unavailable, or if a migration
   * fails.
   */
  public connect(dbPath: string = ':memory:'): void {
    if (this.dbInstance) {
      return;
    }

    if (dbPath !== ':memory:' && !dbPath.startsWith('file::memory:')) {
      const dir = dirname(dbPath);
      mkdirSync(dir, { recursive: true });
    }

    this.dbInstance = new Database(dbPath);
    this.dbInstance.pragma('foreign_keys = ON');
    this.dbInstance.pragma('journal_mode = WAL');

    this.assertJson1Supported();
    runMigrations(this.dbInstance);
  }

  /**
   * Verifies that SQLite JSON1 functions are available and functional.
   *
   * Checked at connection time rather than at first use: the schema stores tags
   * and model parameters as JSON `TEXT` and queries them with `json_valid` and
   * friends, so a build of `better-sqlite3` without JSON1 would fail later, in
   * an unrelated-looking request. Probed by running a query rather than by
   * reading a compile option, since that is what the queries actually need.
   *
   * @throws Error if no connection is open, or if the probe query does not
   * return the expected result.
   */
  public assertJson1Supported(): void {
    if (!this.dbInstance) {
      throw new Error('Database is not initialized');
    }

    try {
      const probe = this.dbInstance
        .prepare("SELECT json_valid('[]') AS valid")
        .get() as { valid: number } | undefined;
      if (probe?.valid !== 1) {
        throw new Error('JSON1 probe query returned unexpected result');
      }
    } catch (error) {
      throw new Error(
        `SQLite JSON1 extension is required but not functional: ${error instanceof Error ? error.message : String(error)}`,
      );
    }
  }

  /**
   * Cleanly closes the database connection.
   */
  public close(): void {
    if (this.dbInstance?.open) {
      this.dbInstance.close();
    }
    this.dbInstance = undefined;
  }

  /**
   * Direct access to the underlying `better-sqlite3` instance.
   *
   * For the few operations this wrapper does not cover, such as the backup and
   * restore paths. Prefer {@link get}, {@link all}, {@link run} and
   * {@link transaction}.
   *
   * @throws Error if no connection is open.
   */
  public get db(): Database.Database {
    if (!this.dbInstance) {
      throw new Error(
        'Database is not initialized. Call connect() or let NestJS module initialization run.',
      );
    }
    return this.dbInstance;
  }

  /**
   * Executes raw DDL or multi-statement SQL scripts.
   *
   * Takes no parameters, so nothing derived from a request may be interpolated
   * into the string. For migrations and fixtures only.
   */
  public exec(sql: string): void {
    this.db.exec(sql);
  }

  /**
   * Retrieves a single row matching the SQL query.
   *
   * @param params - Bound values, positional as an array or named as an object.
   * @returns The first matching row, or `undefined` when there is none.
   */
  public get<T = unknown>(
    sql: string,
    params?: any[] | Record<string, any>,
  ): T | undefined {
    const stmt = this.db.prepare(sql);
    if (params === undefined) {
      return stmt.get() as T | undefined;
    }
    return (
      Array.isArray(params) ? stmt.get(...params) : stmt.get(params)
    ) as T | undefined;
  }

  /**
   * Retrieves all rows matching the SQL query.
   *
   * Materialises the whole result, so list endpoints must apply their own
   * `LIMIT` — see `buildPaginationSqlFragment`.
   *
   * @param params - Bound values, positional as an array or named as an object.
   */
  public all<T = unknown>(
    sql: string,
    params?: any[] | Record<string, any>,
  ): T[] {
    const stmt = this.db.prepare(sql);
    if (params === undefined) {
      return stmt.all() as T[];
    }
    return (
      Array.isArray(params) ? stmt.all(...params) : stmt.all(params)
    ) as T[];
  }

  /**
   * Executes a state-modifying query (INSERT, UPDATE, DELETE).
   *
   * @param params - Bound values, positional as an array or named as an object.
   * @returns The number of affected rows and the last inserted rowid.
   */
  public run(
    sql: string,
    params?: any[] | Record<string, any>,
  ): RunResult {
    const stmt = this.db.prepare(sql);
    const result =
      params === undefined
        ? stmt.run()
        : Array.isArray(params)
          ? stmt.run(...params)
          : stmt.run(params);

    return {
      changes: result.changes,
      lastInsertRowid: result.lastInsertRowid,
    };
  }

  /**
   * Executes a callback within a SQLite transaction.
   *
   * The callback runs synchronously and its return value becomes this method's.
   * A throw rolls the transaction back and propagates, which is how services
   * turn a failed foreign-key check into a 422 without leaving a half-written
   * row behind.
   *
   * The callback must not await. `better-sqlite3` transactions are synchronous
   * and the driver rejects a callback that returns a promise, so an `async`
   * service method has to do its awaiting outside the transaction — which is
   * why the picture endpoints write to storage and to the database in separate
   * steps.
   */
  public transaction<T>(fn: () => T): T {
    const trx = this.db.transaction(fn);
    return trx();
  }
}
